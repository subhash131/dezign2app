import React, { useState, useMemo, useCallback } from "react";
import { useBackendCanvasStore } from "@/lib/stores/backendCanvasStore";
import { DbOperationFunction } from "@workspace/canvas/types";
import {
  generateDefaultDbOperationsForEngine,
  generateRedisOperations,
  getEntityDbOperations,
} from "@/lib/utils/entityOperationsHelper";
import { getEntityDbConnectionInfo } from "@/lib/stores/dbSyncStore";
import {
  AlertDialog,
  AlertDialogAction,
  AlertDialogCancel,
  AlertDialogContent,
  AlertDialogDescription,
  AlertDialogFooter,
  AlertDialogHeader,
  AlertDialogTitle,
} from "@workspace/ui/components/alert-dialog";
import { FunctionDetailEditor } from "./FunctionDetailEditor";
import { EntityFunctionsList } from "./EntityFunctionsList";
import { EntityGroupSelect } from "../../backend-nodes/entity-node/EntityGroupSelect";
import {
  buildDefaultDbPromptContext,
  TableSchemaInfo,
} from "../../shared/BusinessLogicBlock";

export interface EntityFunctionsConfigProps {
  id?: string;
  nodeId: string;
}

const EntityFunctionsConfigContent: React.FC<{
  node: NonNullable<ReturnType<typeof useBackendCanvasStore.getState>["nodes"][0]>;
  nodeId: string;
}> = ({ node, nodeId }) => {
  const updateNode = useBackendCanvasStore((s) => s.updateNode);
  const allNodes = useBackendCanvasStore((s) => s.nodes);
  const edges = useBackendCanvasStore((s) => s.edges);

  // Selected operation ID for detail editing view
  const [selectedOpId, setSelectedOpId] = useState<string | null>(null);
  const [isNewOp, setIsNewOp] = useState<boolean>(false);
  const [opToDelete, setOpToDelete] = useState<{ id: string; name: string } | null>(null);

  const isRedis =
    node.type === "redis_schema" ||
    node.data?.dbType === "redis" ||
    node.data?.dbEngine === "redis";

  const label = node.data.label || (isRedis ? "Cache" : "Table");
  const columns = node.data.columns || [];
  const indexes = node.data.indexes || [];
  const pascalLabel = label.charAt(0).toUpperCase() + label.slice(1);

  // Resolve parent database / redis_instance node and connection info using the same logic as Validate DB and DDL execution
  const dbInfo = useMemo(() => {
    return getEntityDbConnectionInfo(node, allNodes);
  }, [node, allNodes]);

  const parentDb = useMemo(() => {
    if (dbInfo?.dbNode) return dbInfo.dbNode;
    return (
      allNodes.find((n) => n.id === node.data.databaseId) ||
      allNodes.find((n) =>
        edges.some(
          (e) =>
            e.target === nodeId &&
            e.source === n.id &&
            (n.type === "database" || n.type === "redis_instance"),
        ),
      ) ||
      allNodes.find((n) =>
        isRedis
          ? n.type === "redis_instance" || n.data?.dbEngine === "redis"
          : n.type === "database",
      )
    );
  }, [dbInfo, allNodes, edges, nodeId, node.data.databaseId, isRedis]);

  const dbType = dbInfo?.engine || (isRedis
    ? "redis"
    : (parentDb?.data?.dbEngine || parentDb?.data?.dbType || "postgres"));

  const schema = dbInfo?.schema || node.data.schema || parentDb?.data?.schema || "public";

  const currentOps: DbOperationFunction[] =
    node.data.dbOperations && node.data.dbOperations.length > 0
      ? getEntityDbOperations(node, allNodes, dbType)
      : isRedis
        ? generateRedisOperations(label, node.data)
        : generateDefaultDbOperationsForEngine(label, columns, indexes, allNodes, dbType);

  const selectedOp = currentOps.find((op) => op.id === selectedOpId);

  const saveOps = useCallback(
    (updated: DbOperationFunction[]) => {
      updateNode(nodeId, {
        data: {
          ...node.data,
          dbOperations: updated,
        },
      });
    },
    [nodeId, node.data, updateNode],
  );

  const updateSelectedOp = useCallback(
    (changes: Partial<DbOperationFunction>) => {
      if (!selectedOpId) return;
      const updated = currentOps.map((op) =>
        op.id === selectedOpId ? { ...op, ...changes } : op,
      );
      saveOps(updated);
    },
    [selectedOpId, currentOps, saveOps],
  );

  const handleRegenerateDefaults = () => {
    const defaults = isRedis
      ? generateRedisOperations(label, node.data)
      : generateDefaultDbOperationsForEngine(label, columns, indexes, allNodes, dbType);
    const customOps = currentOps.filter((op) => !op.isAutoGenerated);
    saveOps([...defaults, ...customOps]);
  };

  const handleToggle = (opId: string, enabled: boolean) => {
    const updated = currentOps.map((op) =>
      op.id === opId ? { ...op, enabled } : op,
    );
    saveOps(updated);
  };

  const handleDeleteOp = (opId: string) => {
    const updated = currentOps.filter((op) => op.id !== opId);
    saveOps(updated);
    if (selectedOpId === opId) setSelectedOpId(null);
  };

  const handleCreateNewFunction = () => {
    const defaultPrompt = isRedis
      ? `Execute Redis operation for ${label}`
      : buildDefaultDbPromptContext({
          dbType,
          tableName: label,
          columns,
          indexes,
          operation: {
            name: `custom${pascalLabel}Query`,
            kind: "custom",
            description: `Custom database query for ${label}`,
            params: [],
            returnType: `${pascalLabel}[]`,
          },
        });

    const newOp: DbOperationFunction = {
      id: `custom-op-${Date.now()}`,
      name: "",
      kind: "custom",
      description: isRedis ? `Custom Redis operation for ${label}` : `Custom database query for ${label}`,
      returnTypeMode: "inferred",
      returnType: isRedis ? `Promise<${pascalLabel} | null>` : `${pascalLabel}[]`,
      params: isRedis ? [{ name: "key", type: "string", required: true }] : [],
      pagination: {
        enabled: false,
        defaultLimit: 20,
        maxLimit: 100,
        mode: "offset",
      },
      logicMode: isRedis ? "code" : "natural_language",
      prompt: defaultPrompt,
      code: isRedis
        ? `export async function custom${pascalLabel}Op(key: string): Promise<${pascalLabel} | null> {\n  const redis = await getRedisClient();\n  const raw = await redis.get(key);\n  return raw ? JSON.parse(raw) : null;\n}`
        : "",
      enabled: true,
      isAutoGenerated: false,
    };

    saveOps([...currentOps, newOp]);
    setSelectedOpId(newOp.id);
    setIsNewOp(true);
  };

  // Sync pagination parameters into function params when pagination toggling occurs
  const handleTogglePagination = useCallback(
    (enabled: boolean) => {
      if (!selectedOp) return;
      const currentPagination = selectedOp.pagination || {
        defaultLimit: 20,
        maxLimit: 100,
        mode: "offset",
      };

      let params = selectedOp.params || [];

      if (enabled) {
        const mode = currentPagination.mode || "offset";
        const hasLimit = params.some((p) => p.name === "limit");
        const hasOffset = params.some((p) => p.name === "offset");
        const hasCursor = params.some((p) => p.name === "cursor");

        const newParams = [...params];
        if (!hasLimit) {
          newParams.push({
            name: "limit",
            type: "number",
            required: false,
            defaultValue: String(currentPagination.defaultLimit ?? 20),
          });
        }
        if (mode === "offset" && !hasOffset) {
          newParams.push({
            name: "offset",
            type: "number",
            required: false,
            defaultValue: "0",
          });
        } else if (mode === "cursor" && !hasCursor) {
          newParams.push({
            name: "cursor",
            type: "string",
            required: false,
          });
        }

        params = newParams;
      } else {
        params = params.filter(
          (p) => p.name !== "limit" && p.name !== "offset" && p.name !== "cursor",
        );
      }

      updateSelectedOp({
        pagination: { ...currentPagination, enabled },
        params,
      });
    },
    [selectedOp, updateSelectedOp],
  );

  // Sync parameters when pagination mode changes (offset vs cursor)
  const handleChangePaginationMode = useCallback(
    (mode: "offset" | "cursor") => {
      if (!selectedOp) return;
      let params = selectedOp.params || [];
      if (mode === "offset") {
        params = params.filter((p) => p.name !== "cursor");
        if (!params.some((p) => p.name === "offset")) {
          params.push({
            name: "offset",
            type: "number",
            required: false,
            defaultValue: "0",
          });
        }
      } else {
        params = params.filter((p) => p.name !== "offset");
        if (!params.some((p) => p.name === "cursor")) {
          params.push({
            name: "cursor",
            type: "string",
            required: false,
          });
        }
      }

      updateSelectedOp({
        pagination: {
          ...(selectedOp.pagination || {
            enabled: true,
            defaultLimit: 20,
            maxLimit: 100,
          }),
          mode,
        },
        params,
      });
    },
    [selectedOp, updateSelectedOp],
  );

  // Available table nodes for BusinessLogicBlock context
  const availableTableNodes = useMemo(
    () =>
      allNodes
        .filter((n) => n?.type === "entity")
        .map((n) => ({
          id: n.id,
          label: n.data?.label || "Table",
        })),
    [allNodes],
  );

  const allTableSchemas = useMemo((): TableSchemaInfo[] => {
    return allNodes
      .filter((n) => n?.type === "entity" || n?.type === "redis_schema")
      .map((n) => ({
        id: n.id,
        name: n.data?.label || (n.type === "redis_schema" ? "Cache" : "Table"),
        dbType: n.type === "redis_schema" ? "redis" : (n.data?.dbType || "relational"),
        columns: n.data?.columns || [],
        indexes: n.data?.indexes || [],
      }));
  }, [allNodes]);

  const autoOps = currentOps.filter((op) => op.isAutoGenerated);
  const customOps = currentOps.filter((op) => !op.isAutoGenerated);

  return (
    <>
      {selectedOp ? (
        <FunctionDetailEditor
          key={selectedOp.id}
          selectedOp={selectedOp}
          isNew={isNewOp}
          onCancelNew={() => {
            handleDeleteOp(selectedOp.id);
            setIsNewOp(false);
          }}
          onSaveNew={() => {
            setIsNewOp(false);
          }}
          label={label}
          schema={schema}
          columns={columns}
          indexes={indexes}
          dbType={dbType}
          pascalLabel={pascalLabel}
          availableTableNodes={availableTableNodes}
          allTableSchemas={allTableSchemas}
          parentDb={parentDb}
          allNodes={allNodes}
          onBack={() => {
            setSelectedOpId(null);
            setIsNewOp(false);
          }}
          updateSelectedOp={updateSelectedOp}
          handleTogglePagination={handleTogglePagination}
          handleChangePaginationMode={handleChangePaginationMode}
          onDeleteRequest={(op) => setOpToDelete(op)}
        />
      ) : (
        <div className="space-y-4">
          <EntityGroupSelect
            nodeId={nodeId}
            variant="sidebar"
            readOnly={node.data?.readOnly}
          />
          <EntityFunctionsList
            label={label}
            autoOps={autoOps}
            customOps={customOps}
            onSelectOp={(id) => {
              setSelectedOpId(id);
              setIsNewOp(false);
            }}
            onToggle={handleToggle}
            onRegenerateDefaults={handleRegenerateDefaults}
            onCreateNewFunction={handleCreateNewFunction}
            onDeleteRequest={(op) => setOpToDelete(op)}
          />
        </div>
      )}

      {/* Delete Function Confirmation Dialog */}
      <AlertDialog
        open={!!opToDelete}
        onOpenChange={(open) => !open && setOpToDelete(null)}
      >
        <AlertDialogContent
          onClick={(e) => e.stopPropagation()}
          className="bg-[#111216] border-zinc-800 text-zinc-100 max-w-md shadow-2xl ring-1 ring-white/10"
        >
          <AlertDialogHeader>
            <AlertDialogTitle className="text-zinc-100 font-semibold">
              Delete Function "{opToDelete?.name}"?
            </AlertDialogTitle>
            <AlertDialogDescription className="text-zinc-400 text-xs leading-relaxed">
              Are you sure you want to delete this database operation function? Any logic calling this function will need to be updated.
            </AlertDialogDescription>
          </AlertDialogHeader>
          <AlertDialogFooter>
            <AlertDialogCancel
              onClick={() => setOpToDelete(null)}
              className="bg-zinc-800 hover:bg-zinc-700 text-zinc-300 border-zinc-700 hover:text-zinc-100"
            >
              Cancel
            </AlertDialogCancel>
            <AlertDialogAction
              onClick={() => {
                if (opToDelete) {
                  handleDeleteOp(opToDelete.id);
                  setOpToDelete(null);
                }
              }}
              className="bg-destructive hover:bg-destructive/90 text-destructive-foreground font-semibold"
            >
              Delete Function
            </AlertDialogAction>
          </AlertDialogFooter>
        </AlertDialogContent>
      </AlertDialog>
    </>
  );
};

export const EntityFunctionsConfig: React.FC<EntityFunctionsConfigProps> = ({
  nodeId,
}) => {
  const node = useBackendCanvasStore((s) =>
    s.nodes.find((n) => n.id === nodeId),
  );

  if (!node || (node.type !== "entity" && node.type !== "redis_schema")) {
    return (
      <div className="p-4 text-sm text-muted-foreground">
        Entity node not found.
      </div>
    );
  }

  return <EntityFunctionsConfigContent node={node} nodeId={nodeId} />;
};
