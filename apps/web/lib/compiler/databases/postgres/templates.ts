    "  validateTable,",
    "  validateDatabase,",
    "  validateAll,",
    "  applyTableSync,",
    "  syncAll,",
    "  TABLE_DEFINITIONS,",
    "  TableDefinition,",
    '} from "../sync";',
    "",
    "const PORT = 9000;",
    "",
    "function sendJson(res: http.ServerResponse, statusCode: number, data: object): void {",
