/**
 * Generates the connection.ts file containing the PostgreSQL pool, query helper,
 * transaction wrapper, health checker, and startup auto-migrations.
 */
export function generateConnectionFile(
  packageName: string,
  connEnvKey: string,
  tableSchemas: Record<string, Array<{ name: string; pgType: string }>>,
): string {
  const tableSchemasJson = JSON.stringify(tableSchemas, null, 2);

  return [
    "/**",
    ` * ${packageName}/connection.ts — PostgreSQL connection pool via 'pg'`,
    " *",
    " * Provides a shared Pool, parameterized query helper, transaction wrapper,",
    " * and automatic schema migration on first connection.",
    " */",
    'import "dotenv/config";',
    `import { Pool, PoolClient, QueryResult, QueryResultRow } from "pg";`,
    `import { logger } from "@workspace/logger";`,
    "",
    "export type SqlParam = string | number | boolean | null | undefined | Date;",
    "",
    "const rawConn =",
    `  process.env.${connEnvKey} ||`,
    `  process.env.DATABASE_URL;`,
    "const connectionString =",
    '  rawConn && (rawConn.startsWith("postgres://") || rawConn.startsWith("postgresql://"))',
    "    ? rawConn",
    '    : "postgresql://postgres:postgres@localhost:5432/postgres";',
    "",
    "const isCloudDb =",
    "  Boolean(connectionString && (",
    '    connectionString.includes("supabase.co") ||',
    '    connectionString.includes("pooler.supabase.com") ||',
    '    connectionString.includes("neon.tech") ||',
    '    connectionString.includes("aws.com") ||',
    '    connectionString.includes("rds.amazonaws.com") ||',
    '    connectionString.includes("sslmode=require")',
    "  ));",
    "",
    "export const pool = new Pool({",
    "  connectionString,",
    "  max: 20,",
    "  idleTimeoutMillis: 30000,",
    "  connectionTimeoutMillis: 5000,",
    "  ssl: (process.env.NODE_ENV === 'production' || isCloudDb) ? { rejectUnauthorized: false } : undefined,",
    "});",
    "export interface PreparedStatement<T = Record<string, SqlParam>> {",
    "  get(...params: SqlParam[]): Promise<T | undefined>;",
    "  all(...params: SqlParam[]): Promise<T[]>;",
    "  run(...params: SqlParam[]): Promise<{ changes: number; rowCount: number }>;",
    "}",
    "",
    'declare module "pg" {',
    "  interface Pool {",
    "    prepare<T = Record<string, SqlParam>>(sql: string): PreparedStatement<T>;",
    "  }",
    "}",
    "",
    "pool.prepare = function prepare<T = Record<string, SqlParam>>(sql: string): PreparedStatement<T> {",
    "  let paramIndex = 1;",
    "  const pgSql = sql.replace(/\\?/g, () => `$${paramIndex++}`);",
    "  return {",
    "    async get(...params: SqlParam[]): Promise<T | undefined> {",
    "      const res = await query<T>(pgSql, params);",
    "      return res.rows[0];",
    "    },",
    "    async all(...params: SqlParam[]): Promise<T[]> {",
    "      const res = await query<T>(pgSql, params);",
    "      return res.rows;",
    "    },",
    "    async run(...params: SqlParam[]): Promise<{ changes: number; rowCount: number }> {",
    "      const res = await query(pgSql, params);",
    "      return { changes: res.rowCount ?? 0, rowCount: res.rowCount ?? 0 };",
    "    },",
    "  };",
    "};",
    "",
    "/** Better-Auth and generic ORM compatibility alias */",
    "export const db = pool;",
    "",
    "pool.on('error', (err) => {",
    "  logger.error('Unexpected error on idle PostgreSQL client', { error: err.message });",
    "});",
    "",
    "/**",
    " * Execute a single parameterized SQL query.",
    " */",
    "export async function query<R extends QueryResultRow = Record<string, SqlParam>>(",
    "  text: string,",
    "  params?: SqlParam[]",
    "): Promise<QueryResult<R>> {",
    "  const start = Date.now();",
    "  try {",
    "    const res = await pool.query<R>(text, params);",
    "    const duration = Date.now() - start;",
    "    logger.debug('Executed PostgreSQL query', { text, duration, rows: res.rowCount });",
    "    return res;",
    "  } catch (error) {",
    "    logger.error('PostgreSQL query error', { text, error });",
    "    throw error;",
    "  }",
    "}",
    "",
    "/**",
    " * Execute multiple queries atomically in a single transaction.",
    " *",
    " * @example",
    " * const result = await withTransaction(async (client) => {",
    " *   await client.query('INSERT INTO ...');",
    " *   const res = await client.query('SELECT ...');",
    " *   return res.rows;",
    " * });",
    " */",
    "export async function withTransaction<T>(",
    "  callback: (client: PoolClient) => Promise<T>",
    "): Promise<T> {",
    "  const client = await pool.connect();",
    "  try {",
    "    await client.query('BEGIN');",
    "    const result = await callback(client);",
    "    await client.query('COMMIT');",
    "    return result;",
    "  } catch (error) {",
    "    await client.query('ROLLBACK');",
    "    logger.error('Transaction rolled back', { error });",
    "    throw error;",
    "  } finally {",
    "    client.release();",
    "  }",
    "}",
    "",
    "/**",
    " * Health check — verifies the pool can reach the PostgreSQL server.",
    " */",
    "export async function checkPostgresHealth(): Promise<{",
    "  healthy: boolean;",
    "  latencyMs: number;",
    "  version?: string;",
    "  database?: string;",
    "}> {",
    "  const start = Date.now();",
    "  try {",
    "    const res = await pool.query<{ version: string; current_database: string }>(",
    "      'SELECT version(), current_database()'",
    "    );",
    "    return {",
    "      healthy: true,",
    "      latencyMs: Date.now() - start,",
    "      version: res.rows[0]?.version,",
    "      database: res.rows[0]?.current_database,",
    "    };",
    "  } catch (error) {",
    "    logger.error('PostgreSQL health check failed', { error });",
    "    return { healthy: false, latencyMs: Date.now() - start };",
    "  }",
    "}",
    "",
    "// ── Auto-migration on startup ─────────────────────────────────────────────",
    "// Ensure all declared columns exist on already-created tables.",
    "// This runs once on module load and is safe to call repeatedly.",
    `const _tableSchemas: Record<string, Array<{ name: string; pgType: string }>> = ${tableSchemasJson};`,
    "",
    "(async () => {",
    "  try {",
    "    for (const [tableName, columns] of Object.entries(_tableSchemas)) {",
    "      for (const col of columns) {",
    "        try {",
    "          await pool.query(",
    "            \`ALTER TABLE \\\"\${tableName}\\\" ADD COLUMN IF NOT EXISTS \\\"\${col.name}\\\" \${col.pgType}\`,",
    "          );",
    "        } catch {",
    "          // Column exists or table not yet created — safe to ignore",
    "        }",
    "      }",
    "    }",
    "  } catch {",
    "    // Database may not be ready yet; migrations will retry on next startup",
    "  }",
    "})();",
    "",
    "/** Better-Auth session and user resolution helpers for requireAuth middleware */",
    "export interface AuthSessionRecord {",
    "  userId: string;",
    "  expiresAt: string | Date;",
    "}",
    "",
    "export interface AuthUserRecord {",
    "  id?: string;",
    "  role?: string;",
    "  email?: string;",
    "  name?: string;",
    "  username?: string;",
    "}",
    "",
    "export async function findAuthSessionByToken(token: string): Promise<AuthSessionRecord | null> {",
    "  try {",
    "    const res = await pool.query<{ userId?: string; userid?: string; expiresAt?: string; expiresat?: string }>(",
    "      'SELECT \"userId\", \"expiresAt\" FROM \"session\" WHERE \"token\" = $1 LIMIT 1',",
    "      [token]",
    "    );",
    "    const row = res.rows?.[0];",
    "    if (!row) return null;",
    "    const userId = row.userId ?? row.userid;",
    "    const expiresAt = row.expiresAt ?? row.expiresat;",
    "    if (!userId || !expiresAt) return null;",
    "    return { userId, expiresAt };",
    "  } catch (_quoteErr) {",
    "    try {",
    "      const res = await pool.query<{ userId?: string; expiresAt?: string }>(",
    "        'SELECT userid as \"userId\", expiresat as \"expiresAt\" FROM \"session\" WHERE token = $1 LIMIT 1',",
    "        [token]",
    "      );",
    "      const row = res.rows?.[0];",
    "      if (!row || !row.userId || !row.expiresAt) return null;",
    "      return { userId: row.userId, expiresAt: row.expiresAt };",
    "    } catch {",
    "      return null;",
    "    }",
    "  }",
    "}",
    "",
    "export async function findAuthUserById(userId: string): Promise<AuthUserRecord | null> {",
    "  try {",
    "    const res = await pool.query<{ role?: string; email?: string; name?: string; username?: string }>(",
    "      'SELECT \"role\", \"email\", \"name\" FROM \"user\" WHERE \"id\" = $1 LIMIT 1',",
    "      [userId]",
    "    );",
    "    const row = res.rows?.[0];",
    "    if (!row) return null;",
    "    return {",
    "      role: row.role ?? \"user\",",
    "      email: row.email,",
    "      name: row.name,",
    "      username: row.username,",
    "    };",
    "  } catch (_quoteErr) {",
    "    try {",
    "      const res = await pool.query<{ role?: string; email?: string; name?: string; username?: string }>(",
    "        'SELECT role, email, name FROM \"user\" WHERE id = $1 LIMIT 1',",
    "        [userId]",
    "      );",
    "      const row = res.rows?.[0];",
    "      if (!row) return null;",
    "      return {",
    "        role: row.role ?? \"user\",",
    "        email: row.email,",
    "        name: row.name,",
    "        username: row.username,",
    "      };",
    "    } catch {",
    "      return null;",
    "    }",
    "  }",
    "}",
  ].join("\n");
}

/**
 * Generates the sync.ts file containing programmatic local database sync and validation functions.
 */
export function generateLocalSyncFile(
  packageName: string,
  connEnvKey: string,
  tableDefinitionsJson: string,
): string {
  return [
    "/**",
    ` * ${packageName}/sync.ts — Local Database Validation and Synchronization Functions`,
    " *",
    " * Executes schema inspection, drift detection, and migrations directly on the developer machine.",
    " * Connects natively via 'pg' with full support for Supabase, Neon, AWS RDS, Docker, and Localhost.",
    " */",
    'import "dotenv/config";',
    'import { Client } from "pg";',
    "",
    "export interface ColumnDefinition {",
    "  name: string;",
    "  type: string;",
    "  isPrimaryKey?: boolean;",
    "  isNotNull?: boolean;",
    "  isUnique?: boolean;",
    "  isForeignKey?: boolean;",
    "  references?: {",
    "    table: string;",
    "    column: string;",
    "  };",
    "}",
    "",
    "export interface IndexDefinition {",
    "  name: string;",
    "  columns: string;",
    "  isUnique?: boolean;",
    "}",
    "",
    "export interface ForeignKeyDefinition {",
    "  name?: string;",
    "  column: string;",
    "  foreignTable: string;",
    "  foreignColumn: string;",
    "  foreignSchema?: string;",
    "  onDelete?: string;",
    "  onUpdate?: string;",
    "}",
    "",
    "export interface TableDefinition {",
    "  tableName: string;",
    "  schema?: string;",
    "  columns: ColumnDefinition[];",
    "  indexes?: IndexDefinition[];",
    "  foreignKeys?: ForeignKeyDefinition[];",
    "}",
    "",
    "export interface AlteredColumnDefinition {",
    "  name: string;",
    "  oldType: string;",
    "  newType: string;",
    "}",
    "",
    "export interface CheckDbTableSyncResult {",
    "  success: boolean;",
    "  serverReachable: boolean;",
    "  tableExists: boolean;",
    "  inSync: boolean;",
    "  missingColumns: string[];",
    "  alteredColumns: AlteredColumnDefinition[];",
    "  extraColumns: string[];",
    "  existingColumns: string[];",
    "  missingIndexes: IndexDefinition[];",
    "  extraIndexes: IndexDefinition[];",
    "  existingIndexes: IndexDefinition[];",
    "  missingForeignKeys: ForeignKeyDefinition[];",
    "  extraForeignKeys: ForeignKeyDefinition[];",
    "  existingForeignKeys: ForeignKeyDefinition[];",
    "  missingPrerequisiteTables: string[];",
    "  error?: string;",
    "}",
    "",
    "export interface ApplyDbTableSyncResult {",
    "  success: boolean;",
    "  createdTable: boolean;",
    "  appliedColumns: string[];",
    "  alteredColumns?: AlteredColumnDefinition[];",
    "  appliedIndexes?: string[];",
    "  appliedForeignKeys?: string[];",
    "  appliedPrerequisiteTables?: string[];",
    "  error?: string;",
    "}",
    "",
    "export interface DatabaseValidationSummary {",
    "  total: number;",
    "  inSync: number;",
    "  outOfSync: number;",
    "  errors: number;",
    "  results: Record<string, CheckDbTableSyncResult>;",
    "}",
    "",
    "export interface DatabaseSyncSummary {",
    "  total: number;",
    "  synced: number;",
    "  errors: number;",
    "  results: Record<string, ApplyDbTableSyncResult>;",
    "}",
    "",
    `export const TABLE_DEFINITIONS: Record<string, TableDefinition> = ${tableDefinitionsJson};`,
    "",
    "export function mapToPgType(typeStr: string): string {",
    "  const t = typeStr.toLowerCase().trim();",
    '  if (t === "string" || t === "text" || t === "varchar") return "TEXT";',
    '  if (t === "number" || t === "int" || t === "integer") return "INTEGER";',
    '  if (t === "bigint") return "BIGINT";',
    '  if (t === "float" || t === "double" || t === "decimal") return "DOUBLE PRECISION";',
    '  if (t === "boolean" || t === "bool") return "BOOLEAN";',
    '  if (t === "timestamp" || t === "datetime") return "TIMESTAMPTZ";',
    '  if (t === "json" || t === "jsonb" || t === "object") return "JSONB";',
    '  if (t === "uuid") return "UUID";',
    '  return "TEXT";',
    "}",
    "",
    "export function areTypesEquivalent(cType: string, dbType: string): boolean {",
    "  const normC = mapToPgType(cType);",
    "  const normDb = dbType.toUpperCase().trim();",
    "  if (normC === normDb) return true;",
    '  if (normC === "TEXT" && (normDb.includes("VARCHAR") || normDb.includes("CHAR") || normDb === "TEXT")) return true;',
    '  if (normC === "INTEGER" && (normDb === "INT4" || normDb === "INT" || normDb === "INTEGER" || normDb.includes("SERIAL"))) return true;',
    '  if (normC === "BIGINT" && (normDb === "INT8" || normDb === "BIGINT" || normDb.includes("BIGSERIAL"))) return true;',
    '  if (normC === "DOUBLE PRECISION" && (normDb.includes("DOUBLE") || normDb.includes("FLOAT") || normDb.includes("NUMERIC"))) return true;',
    '  if (normC === "TIMESTAMPTZ" && (normDb.includes("TIMESTAMP") || normDb.includes("DATE"))) return true;',
    '  if (normC === "JSONB" && (normDb === "JSON" || normDb === "JSONB")) return true;',
    "  return false;",
    "}",
    "",
    "export function createClient(customConnectionString?: string): { client: Client; connectionString: string } {",
    `  const rawConn = customConnectionString || process.env.${connEnvKey} || process.env.DATABASE_URL;`,
    "  const connectionString =",
    '    rawConn && (rawConn.startsWith("postgres://") || rawConn.startsWith("postgresql://"))',
    "      ? rawConn",
    '      : "postgresql://postgres:postgres@localhost:5432/postgres";',
    '  const isLocal = connectionString.includes("localhost") || connectionString.includes("127.0.0.1");',
    "  const client = new Client({",
    "    connectionString,",
    "    ssl: isLocal ? undefined : { rejectUnauthorized: false },",
    "  });",
    "  return { client, connectionString };",
    "}",
    "",
    "export async function checkConnection(customConnectionString?: string): Promise<{ success: boolean; latencyMs: number; error?: string }> {",
    "  const start = Date.now();",
    "  const { client } = createClient(customConnectionString);",
    "  try {",
    "    await client.connect();",
    '    await client.query("SELECT 1");',
    "    return { success: true, latencyMs: Date.now() - start };",
    "  } catch (err) {",
    "    return { success: false, latencyMs: Date.now() - start, error: err instanceof Error ? err.message : String(err) };",
    "  } finally {",
    "    await client.end().catch(() => {});",
    "  }",
    "}",
    "",
    "export async function validateTable(",
    "  tableName: string,",
    "  customDef?: TableDefinition,",
    "  customConnectionString?: string,",
    "): Promise<CheckDbTableSyncResult> {",
    "  const def = customDef || TABLE_DEFINITIONS[tableName.toLowerCase()] || TABLE_DEFINITIONS[tableName];",
    "  const safeTable = tableName.trim();",
    '  const targetSchema = def?.schema?.trim() || "public";',
    "  const columns = def?.columns || [];",
    "  const indexes = def?.indexes || [];",
    "  const foreignKeys = def?.foreignKeys || [];",
    "  const { client } = createClient(customConnectionString);",
    "",
    "  try {",
    "    await client.connect();",
    "    const tableCheckRes = await client.query<{ exists: boolean }>(",
    "      `SELECT EXISTS (",
    "        SELECT 1 FROM information_schema.tables",
    "        WHERE LOWER(table_name) = LOWER($1) AND table_schema = $2",
    "      ) AS exists`,",
    "      [safeTable, targetSchema],",
    "    );",
    "    const tableExists = Boolean(tableCheckRes.rows[0]?.exists);",
    "",
    "    if (!tableExists) {",
    "      return {",
    "        success: true,",
    "        serverReachable: true,",
    "        tableExists: false,",
    "        inSync: false,",
    "        missingColumns: columns.map((c) => c.name),",
    "        alteredColumns: [],",
    "        extraColumns: [],",
    "        existingColumns: [],",
    "        missingIndexes: indexes,",
    "        extraIndexes: [],",
    "        existingIndexes: [],",
    "        missingForeignKeys: foreignKeys,",
    "        extraForeignKeys: [],",
    "        existingForeignKeys: [],",
    "        missingPrerequisiteTables: [],",
    "      };",
    "    }",
    "",
    "    const colRes = await client.query<{ column_name: string; data_type: string; udt_name: string }>(",
    "      `SELECT column_name, data_type, udt_name",
    "       FROM information_schema.columns",
    "       WHERE LOWER(table_name) = LOWER($1) AND table_schema = $2`,",
    "      [safeTable, targetSchema],",
    "    );",
    "    const dbCols = colRes.rows.map((r) => ({",
    "      name: r.column_name,",
    "      type: r.udt_name || r.data_type,",
    "    }));",
    "    const dbColMap = new Map(dbCols.map((c) => [c.name.toLowerCase(), c.type]));",
    "",
    "    const missingColumns: string[] = [];",
    "    const alteredColumns: AlteredColumnDefinition[] = [];",
    "    const existingColumns: string[] = [];",
    "",
    "    for (const c of columns) {",
    "      const dbType = dbColMap.get(c.name.toLowerCase());",
    "      if (dbType === undefined) {",
    "        missingColumns.push(c.name);",
    "      } else {",
    "        existingColumns.push(c.name);",
    "        if (!areTypesEquivalent(c.type, dbType)) {",
    "          alteredColumns.push({",
    "            name: c.name,",
    "            oldType: dbType,",
    "            newType: mapToPgType(c.type),",
    "          });",
    "        }",
    "      }",
    "    }",
    "",
    "    const canvasColSet = new Set(columns.map((c) => c.name.toLowerCase()));",
    "    const extraColumns = dbCols",
    "      .filter((c) => !canvasColSet.has(c.name.toLowerCase()))",
    "      .map((c) => c.name);",
    "",
    "    const idxRes = await client.query<{ index_name: string; is_unique: boolean; column_names: string }>(",
    "      `SELECT i.relname AS index_name,",
    "              ix.indisunique AS is_unique,",
    "              ARRAY_TO_STRING(ARRAY_AGG(a.attname ORDER BY array_position(ix.indkey, a.attnum)), ', ') AS column_names",
    "       FROM pg_class t",
    "       JOIN pg_index ix ON t.oid = ix.indrelid",
    "       JOIN pg_class i ON i.oid = ix.indexrelid",
    "       JOIN pg_namespace n ON n.oid = t.relnamespace",
    "       JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum = ANY(ix.indkey)",
    "       WHERE LOWER(t.relname) = LOWER($1)",
    "         AND n.nspname = $2",
    "         AND NOT ix.indisprimary",
    "       GROUP BY i.relname, ix.indisunique`,",
    "      [safeTable, targetSchema],",
    "    );",
    "    const dbIndexes = idxRes.rows.map((r) => ({",
    "      name: r.index_name,",
    "      columns: r.column_names,",
    "      isUnique: Boolean(r.is_unique),",
    "    }));",
    "",
    "    const missingIndexes = indexes.filter(",
    "      (cIdx) => !dbIndexes.some((dIdx) => dIdx.columns.toLowerCase() === cIdx.columns.toLowerCase()),",
    "    );",
    "    const extraIndexes = dbIndexes.filter(",
    "      (dIdx) => !indexes.some((cIdx) => cIdx.columns.toLowerCase() === dIdx.columns.toLowerCase()),",
    "    );",
    "    const existingIndexes = dbIndexes.filter(",
    "      (dIdx) => indexes.some((cIdx) => cIdx.columns.toLowerCase() === dIdx.columns.toLowerCase()),",
    "    );",
    "",
    "    const fkRes = await client.query<{",
    "      constraint_name: string;",
    "      column_name: string;",
    "      foreign_table: string;",
    "      foreign_column: string;",
    "    }>(",
    "      `SELECT c.conname AS constraint_name,",
    "              att.attname AS column_name,",
    "              cl_ref.relname AS foreign_table,",
    "              att_ref.attname AS foreign_column",
    "       FROM pg_constraint c",
    "       JOIN pg_class cl ON cl.oid = c.conrelid",
    "       JOIN pg_namespace n ON n.oid = cl.relnamespace",
    "       JOIN pg_attribute att ON att.attrelid = c.conrelid AND att.attnum = ANY(c.conkey)",
    "       JOIN pg_class cl_ref ON cl_ref.oid = c.confrelid",
    "       JOIN pg_namespace n_ref ON n_ref.oid = cl_ref.relnamespace",
    "       JOIN pg_attribute att_ref ON att_ref.attrelid = c.confrelid AND att_ref.attnum = ANY(c.confkey)",
    "       WHERE c.contype = 'f'",
    "         AND LOWER(cl.relname) = LOWER($1)",
    "         AND n.nspname = $2`,",
    "      [safeTable, targetSchema],",
    "    );",
    "    const dbFks = fkRes.rows.map((r) => ({",
    "      name: r.constraint_name,",
    "      column: r.column_name,",
    "      foreignTable: r.foreign_table,",
    "      foreignColumn: r.foreign_column,",
    "    }));",
    "",
    "    const missingForeignKeys = foreignKeys.filter(",
    "      (cFk) =>",
    "        !dbFks.some(",
    "          (dFk) =>",
    "            dFk.column.toLowerCase() === cFk.column.toLowerCase() &&",
    "            dFk.foreignTable.toLowerCase() === cFk.foreignTable.toLowerCase(),",
    "        ),",
    "    );",
    "    const extraForeignKeys = dbFks.filter(",
    "      (dFk) =>",
    "        !foreignKeys.some(",
    "          (cFk) =>",
    "            cFk.column.toLowerCase() === dFk.column.toLowerCase() &&",
    "            cFk.foreignTable.toLowerCase() === dFk.foreignTable.toLowerCase(),",
    "        ),",
    "    );",
    "    const existingForeignKeys = dbFks.filter(",
    "      (dFk) =>",
    "        foreignKeys.some(",
    "          (cFk) =>",
    "            cFk.column.toLowerCase() === dFk.column.toLowerCase() &&",
    "            cFk.foreignTable.toLowerCase() === dFk.foreignTable.toLowerCase(),",
    "        ),",
    "    );",
    "",
    "    const inSync =",
    "      missingColumns.length === 0 &&",
    "      alteredColumns.length === 0 &&",
    "      missingIndexes.length === 0 &&",
    "      missingForeignKeys.length === 0;",
    "",
    "    return {",
    "      success: true,",
    "      serverReachable: true,",
    "      tableExists: true,",
    "      inSync,",
    "      missingColumns,",
    "      alteredColumns,",
    "      extraColumns,",
    "      existingColumns,",
    "      missingIndexes,",
    "      extraIndexes,",
    "      existingIndexes,",
    "      missingForeignKeys,",
    "      extraForeignKeys,",
    "      existingForeignKeys,",
    "      missingPrerequisiteTables: [],",
    "    };",
    "  } catch (err) {",
    "    return {",
    "      success: false,",
    "      serverReachable: false,",
    "      tableExists: false,",
    "      inSync: false,",
    "      missingColumns: [],",
    "      alteredColumns: [],",
    "      extraColumns: [],",
    "      existingColumns: [],",
    "      missingIndexes: indexes,",
    "      extraIndexes: [],",
    "      existingIndexes: [],",
    "      missingForeignKeys: foreignKeys,",
    "      extraForeignKeys: [],",
    "      existingForeignKeys: [],",
    "      missingPrerequisiteTables: [],",
    "      error: err instanceof Error ? err.message : String(err),",
    "    };",
    "  } finally {",
    "    await client.end().catch(() => {});",
    "  }",
    "}",
    "",
    "export async function validateDatabase(customConnectionString?: string): Promise<DatabaseValidationSummary> {",
    "  const tableNames = Object.keys(TABLE_DEFINITIONS);",
    "  let inSync = 0;",
    "  let outOfSync = 0;",
    "  let errors = 0;",
    "  const results: Record<string, CheckDbTableSyncResult> = {};",
    "",
    "  for (const name of tableNames) {",
    "    const res = await validateTable(name, TABLE_DEFINITIONS[name], customConnectionString);",
    "    results[name] = res;",
    "    if (!res.success || !res.serverReachable) {",
    "      errors++;",
    "    } else if (res.inSync) {",
    "      inSync++;",
    "    } else {",
    "      outOfSync++;",
    "    }",
    "  }",
    "",
    "  return {",
    "    total: tableNames.length,",
    "    inSync,",
    "    outOfSync,",
    "    errors,",
    "    results,",
    "  };",
    "}",
    "",
    "export async function validateAll(customConnectionString?: string): Promise<DatabaseValidationSummary> {",
    "  return validateDatabase(customConnectionString);",
    "}",
    "",
    "export async function applyTableSync(",
    "  tableName: string,",
    "  customDef?: TableDefinition,",
    "  customConnectionString?: string,",
    "): Promise<ApplyDbTableSyncResult> {",
    "  const def = customDef || TABLE_DEFINITIONS[tableName.toLowerCase()] || TABLE_DEFINITIONS[tableName];",
    "  const safeTable = tableName.trim();",
    '  const targetSchema = def?.schema?.trim() || "public";',
    "  const columns = def?.columns || [];",
    "  const indexes = def?.indexes || [];",
    "  const foreignKeys = def?.foreignKeys || [];",
    "  const { client } = createClient(customConnectionString);",
    "",
    "  const appliedColumns: string[] = [];",
    "  const alteredColumns: AlteredColumnDefinition[] = [];",
    "  const appliedIndexes: string[] = [];",
    "  const appliedForeignKeys: string[] = [];",
    "  let createdTable = false;",
    "",
    "  try {",
    "    await client.connect();",
    "    const tableChk = await client.query<{ exists: boolean }>(",
    "      `SELECT EXISTS (",
    "        SELECT 1 FROM information_schema.tables",
    "        WHERE LOWER(table_name) = LOWER($1) AND table_schema = $2",
    "      ) AS exists`,",
    "      [safeTable, targetSchema],",
    "    );",
    "",
    "    if (!tableChk.rows[0]?.exists) {",
    "      const colSql = columns.map((c) => {",
    "        const pgType = mapToPgType(c.type);",
    '        let colDef = `"${c.name}" ${pgType}`;',
    '        if (c.isPrimaryKey || c.name.toLowerCase() === "id") colDef += " PRIMARY KEY";',
    '        if (c.isNotNull) colDef += " NOT NULL";',
    '        if (c.isUnique) colDef += " UNIQUE";',
    "        return colDef;",
    "      });",
    '      if (!colSql.some((s) => s.includes("PRIMARY KEY"))) {',
    '        colSql.unshift(\'"id" TEXT PRIMARY KEY\');',
    "      }",
    '      await client.query(`CREATE TABLE IF NOT EXISTS "${targetSchema}"."${safeTable}" (${colSql.join(", ")})`);',
    "      createdTable = true;",
    "    } else {",
    "      const dbColRes = await client.query<{ column_name: string; udt_name: string }>(",
    "        `SELECT column_name, udt_name FROM information_schema.columns",
    "         WHERE LOWER(table_name) = LOWER($1) AND table_schema = $2`,",
    "        [safeTable, targetSchema],",
    "      );",
    "      const dbColMap = new Map(dbColRes.rows.map((r) => [r.column_name.toLowerCase(), r.udt_name]));",
    "",
    "      for (const col of columns) {",
    "        const dbType = dbColMap.get(col.name.toLowerCase());",
    "        const targetType = mapToPgType(col.type);",
    "        if (dbType === undefined) {",
    '          let addDef = `ADD COLUMN IF NOT EXISTS "${col.name}" ${targetType}`;',
    '          if (col.isNotNull && !col.isPrimaryKey) addDef += " NOT NULL DEFAULT \'\'";',
    '          if (col.isUnique) addDef += " UNIQUE";',
    '          await client.query(`ALTER TABLE "${targetSchema}"."${safeTable}" ${addDef}`);',
    "          appliedColumns.push(col.name);",
    "        } else if (!areTypesEquivalent(col.type, dbType)) {",
    "          await client.query(",
    '            `ALTER TABLE "${targetSchema}"."${safeTable}" ALTER COLUMN "${col.name}" TYPE ${targetType} USING "${col.name}"::text::${targetType}`,',
    "          );",
    "          alteredColumns.push({",
    "            name: col.name,",
    "            oldType: dbType,",
    "            newType: targetType,",
    "          });",
    "        }",
    "      }",
    "    }",
    "",
    "    for (const idx of indexes) {",
    "      if (!idx.columns) continue;",
    '      const safeIdxName = idx.name || `idx_${safeTable}_${idx.columns.replace(/[^a-zA-Z0-9_]/g, "_")}`;',
    '      const uniqueKeyword = idx.isUnique ? "UNIQUE " : "";',
    "      const colList = idx.columns",
    "        .split(',')",
    '        .map((c) => `"${c.trim()}"`)',
    '        .join(", ");',
    "      await client.query(",
    '        `CREATE ${uniqueKeyword}INDEX IF NOT EXISTS "${safeIdxName}" ON "${targetSchema}"."${safeTable}" (${colList})`,',
    "      );",
    "      appliedIndexes.push(safeIdxName);",
    "    }",
    "",
    "    for (const fk of foreignKeys) {",
    "      if (!fk.column || !fk.foreignTable || !fk.foreignColumn) continue;",
    '      const safeFkName = fk.name || `fk_${safeTable}_${fk.column}`;',
    '      const fSchema = fk.foreignSchema || targetSchema;',
    '      const onDelete = fk.onDelete || "CASCADE";',
    "      try {",
    "        await client.query(",
    '          `ALTER TABLE "${targetSchema}"."${safeTable}"',
    '           ADD CONSTRAINT "${safeFkName}"',
    '           FOREIGN KEY ("${fk.column}")',
    '           REFERENCES "${fSchema}"."${fk.foreignTable}" ("${fk.foreignColumn}")',
    "           ON DELETE ${onDelete}`,",
    "        );",
    "        appliedForeignKeys.push(safeFkName);",
    "      } catch {",
    "        // Continue if constraint already exists",
    "      }",
    "    }",
    "",
    "    return {",
    "      success: true,",
    "      createdTable,",
    "      appliedColumns,",
    "      alteredColumns,",
    "      appliedIndexes,",
    "      appliedForeignKeys,",
    "    };",
    "  } catch (err) {",
    "    return {",
    "      success: false,",
    "      createdTable: false,",
    "      appliedColumns: [],",
    "      error: err instanceof Error ? err.message : String(err),",
    "    };",
    "  } finally {",
    "    await client.end().catch(() => {});",
    "  }",
    "}",
    "",
    "export async function syncAll(customConnectionString?: string): Promise<DatabaseSyncSummary> {",
    "  const tableNames = Object.keys(TABLE_DEFINITIONS);",
    "  let synced = 0;",
    "  let errors = 0;",
    "  const results: Record<string, ApplyDbTableSyncResult> = {};",
    "",
    "  for (const name of tableNames) {",
    "    const res = await applyTableSync(name, TABLE_DEFINITIONS[name], customConnectionString);",
    "    results[name] = res;",
    "    if (res.success) {",
    "      synced++;",
    "    } else {",
    "      errors++;",
    "    }",
    "  }",
    "",
    "  return {",
    "    total: tableNames.length,",
    "    synced,",
    "    errors,",
    "    results,",
    "  };",
    "}",
  ].join("\n");
}

